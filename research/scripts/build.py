"""Check every note, then rebuild generated/ from the papers' frontmatter.

    uv run scripts/build.py

generated/ is never edited by hand: the notes are the single source of truth.
"""

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PAPERS = ROOT / "papers"
GENERATED = ROOT / "generated"
LINKED_DIRS = ["papers", "topics", "people", "proposal"]

REQUIRED = ["id", "title", "authors", "year", "read", "relevance", "topics"]
CHOICES = {
    "read": {"full", "partial", "abstract", "unverified"},
    "relevance": {"high", "medium", "low"},
}
SETTING_CHOICES = {
    "turn_protocol": {"strict", "natural", "simultaneous", None},
    "stakes": {"none", "opinion", "payoff", "money", None},
}
SETTING_FLAGS = ["multi_turn", "persuasion_treatment", "human_baseline"]
MATRIX_COLUMNS = [
    ("multi_turn", "multi-turn"),
    ("turn_protocol", "turns"),
    ("players", "players"),
    ("stakes", "stakes"),
    ("persuasion_treatment", "persuasion treatment"),
    ("human_baseline", "human baseline"),
]


def frontmatter(path: Path) -> tuple[dict, str]:
    text = path.read_text()
    match = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not match:
        return {}, text
    return yaml.safe_load(match.group(1)) or {}, match.group(2)


def check(path: Path, meta: dict) -> list[str]:
    errors = [f"missing `{field}`" for field in REQUIRED if field not in meta]
    if meta.get("id") != path.stem:
        errors.append(f"id `{meta.get('id')}` must match the file name")
    for field, allowed in CHOICES.items():
        if field in meta and meta[field] not in allowed:
            errors.append(f"`{field}` must be one of {sorted(allowed)}")
    setting = meta.get("setting") or {}
    for field, allowed in SETTING_CHOICES.items():
        if setting.get(field) not in allowed:
            errors.append(f"`setting.{field}` must be one of {sorted(map(str, allowed))}")
    for field in SETTING_FLAGS:
        if setting.get(field) not in (True, False, None):
            errors.append(f"`setting.{field}` must be true, false or empty")
    return [f"{path.relative_to(ROOT)}: {error}" for error in errors]


def broken_links() -> list[str]:
    names = {p.stem for d in LINKED_DIRS for p in (ROOT / d).rglob("*.md")}
    errors = []
    for directory in LINKED_DIRS:
        for path in (ROOT / directory).rglob("*.md"):
            for link in re.findall(r"\[\[([^\]]+)\]\]", path.read_text()):
                if link not in names:
                    errors.append(f"{path.relative_to(ROOT)}: no note named [[{link}]]")
    return errors


def cell(value) -> str:
    if value is None:
        return "?"
    if value is True:
        return "yes"
    if value is False:
        return "no"
    return str(value)


def matrix(papers: list[dict]) -> str:
    header = ["paper", "year", "read", "relevance"] + [label for _, label in MATRIX_COLUMNS]
    lines = [
        "# Literature matrix",
        "",
        "Generated by `scripts/build.py` from the papers' frontmatter; do not edit.",
        "`?` means not recorded yet. Only `read: full` rows are safe to cite in the proposal.",
        "",
        "| " + " | ".join(header) + " |",
        "|" + "---|" * len(header),
    ]
    for meta in sorted(papers, key=lambda m: (-int(m["year"]), m["id"])):
        setting = meta.get("setting") or {}
        row = [
            f"[{meta['id']}](../papers/{meta['id']}.md)",
            str(meta["year"]),
            meta["read"],
            meta["relevance"],
        ] + [cell(setting.get(field)) for field, _ in MATRIX_COLUMNS]
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines) + "\n"


def bibtex(papers: list[dict]) -> str:
    entries = []
    for meta in sorted(papers, key=lambda m: m["id"]):
        fields = {
            "title": "{" + meta["title"] + "}",
            "author": " and ".join(meta["authors"]),
            "year": str(meta["year"]),
        }
        if meta.get("venue"):
            fields["note"] = meta["venue"]
        if meta.get("arxiv"):
            fields["eprint"] = meta["arxiv"]
            fields["archivePrefix"] = "arXiv"
            fields["url"] = f"https://arxiv.org/abs/{meta['arxiv']}"
        elif meta.get("url"):
            fields["url"] = meta["url"]
        body = ",\n".join(f"  {key} = {{{value}}}" for key, value in fields.items())
        entries.append(f"@misc{{{meta['id']},\n{body}\n}}")
    header = "% Generated by scripts/build.py from papers/*.md; do not edit.\n\n"
    return header + "\n\n".join(entries) + "\n"


def main() -> None:
    papers, errors = [], []
    for path in sorted(PAPERS.glob("*.md")):
        meta, _ = frontmatter(path)
        errors += check(path, meta)
        papers.append(meta)
    errors += broken_links()
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    GENERATED.mkdir(exist_ok=True)
    (GENERATED / "matrix.md").write_text(matrix(papers))
    (GENERATED / "references.bib").write_text(bibtex(papers))
    unread = sum(meta["read"] != "full" for meta in papers)
    print(f"{len(papers)} papers, {unread} not yet read in full; generated/ rebuilt")


if __name__ == "__main__":
    main()
